"""Build a synthetic city from its specification (gap items A1, A3, A5).

    python city/generate.py demo          # reads cities/demo/city.yaml

Writes next to the specification (all reproducible from `seed`):
    network.dss      OpenDSS model: one 11 kV source per substation, feeders of cable segments with a
                     sectionaliser half-way, a normally open tie between the far ends of neighbouring feeders
                     (some across substations), transformers with a fixed block a and a movable block b whose
                     home switch keeps it on its own transformer and alt switch moves it to the next one
    consumers.csv    every consumer: consumer ID, meter ID (MTR-xxxxx), transformer, type, size, EV rank
    config/          grid.yaml (assets, IDs, ratings, switches, moves, MV transfers, diagram layout) and the
                     operations, scenarios, forecasting, storage and simulation settings for this city

Sizing: every transformer gets a dominant consumer type and a mix of consumers; their number is chosen so
that the transformer's normal-year peak (no optional events, no noise) is the drawn share of its rating.
"""
