HEADER = "# Generated by city/generate.py from ../city.yaml: edit that file and generate again instead.\n"


def _choice(rng, probs):
    keys = list(probs)
    p = np.asarray([probs[k] for k in keys], dtype=float)
    return keys[rng.choice(len(keys), p=p / p.sum())]


def build(spec):
    """The city as plain data: substations, feeders, transformers (with consumers), switches, moves, ties."""
    rng = np.random.default_rng(int(spec["seed"]))
    net = spec["network"]
    n_sub = int(net["substations"])
    per_sub = list(net["feeders_per_substation"])
    if len(per_sub) != n_sub:
        raise ValueError("city.yaml: feeders_per_substation needs one number per substation")
    subs = [f"S{i + 1}" for i in range(n_sub)]
    feeders, txs = [], []
    counts = [int(rng.integers(net["transformers_per_feeder"]["min"], net["transformers_per_feeder"]["max"] + 1))
              for _ in range(sum(per_sub))]
    width = max(2, len(str(sum(counts))))
    fi = 0
    for si, nf in enumerate(per_sub):
        for _ in range(nf):
            name = f"F{fi + 1}"
            n = counts[fi]
            names = [f"T{len(txs) + j + 1:0{width}d}" for j in range(n)]
            buses = [f"{name}B{j + 1}" for j in range(n)]
            seg = rng.uniform(net["segment_km"]["min"], net["segment_km"]["max"], n).round(2)
            feeders.append({"name": name, "substation": subs[si], "transformers": names, "buses": buses,
                            "segments_km": seg.tolist(), "sec_after": max(1, n // 2)})
            for j, t in enumerate(names):
                txs.append({"name": t, "feeder": name, "mv_bus": buses[j], "lv_bus": f"L{t[1:]}",
                            "rating_kva": int(_choice(rng, net["ratings_kva"])),
                            "type": _choice(rng, spec["consumers"]["transformer_types"]),
                            "utilisation": float(rng.uniform(net["peak_utilisation"]["min"], net["peak_utilisation"]["max"]))})
            fi += 1
    ties = []
    for i in range(0, len(feeders) - 1, 2):
        a, b = feeders[i], feeders[i + 1]
        ties.append({"name": f"TIE{len(ties) + 1}", "a": a["name"], "b": b["name"], "bus_a": a["buses"][-1],
                     "bus_b": b["buses"][-1]})
    return {"rng": rng, "subs": subs, "feeders": feeders, "txs": txs, "ties": ties}


def size_consumers(spec, city, d):
    """Consumers of every transformer, sized so that its normal-year peak is utilisation x rating."""
    rng = city["rng"]
    units, _, _ = d.units(())
    comp = spec["consumers"]["composition"]
    pf = spec["consumers"]["power_factor"]
    sigma = spec["consumers"]["size_spread"]
    rows, n = [], 0
    for tx in city["txs"]:
        shares = comp[tx["type"]]
        mix = sum(s * units[k] for k, s in shares.items())
        target_kw = tx["utilisation"] * tx["rating_kva"] * pf[tx["type"]]
        total = target_kw / float(mix.max())
        for kind, s in shares.items():
            for _ in range(max(1, int(round(total * s)))):
                n += 1
                rows.append({"consumer_id": f"C-{n:05d}", "meter_id": f"MTR-{n:05d}", "transformer": tx["name"],
                             "type": kind, "size": round(float(rng.lognormal(-sigma ** 2 / 2, sigma)), 4),
                             "ev_rank": round(float(rng.uniform()), 4)})
    return pd.DataFrame(rows)


def network_dss(spec, city):
    net, cab = spec["network"], spec["network"]["cable"]
    out = ["Clear"]
    first, *others = city["subs"]
    out.append(f"New Circuit.City basekv=11 pu=1.0 phases=3 bus1={first} MVAsc3={net['source_mvasc']} "
               f"MVAsc1={net['source_mvasc']}")
    for s in others:
        out.append(f"New Vsource.{s} bus1={s} basekv=11 pu=1.0 phases=3 MVAsc3={net['source_mvasc']} "
                   f"MVAsc1={net['source_mvasc']}")
    out.append(f"New Linecode.LC11 nphases=3 r1={cab['r1']} x1={cab['x1']} r0={cab['r0']} x0={cab['x0']} units=km "
               f"normamps={cab['normamps']} emergamps={cab['emergamps']}")
    for f in city["feeders"]:
        out.append(f"\n! Feeder {f['name']} from substation {f['substation']}")
        prev = f["substation"]
        for j, (bus, km) in enumerate(zip(f["buses"], f["segments_km"]), start=1):
            out.append(f"New Line.{f['name']}L{j} bus1={prev} bus2={bus} linecode=LC11 length={km} units=km")
            prev = bus
            if j == f["sec_after"] and j < len(f["buses"]):
                out.append(f"New Line.{f['name']}SEC bus1={bus} bus2={bus}s switch=yes")
                prev = f"{bus}s"
    out.append("\n! Normally open ties between the far ends of neighbouring feeders")
    for t in city["ties"]:
        out.append(f"New Line.{t['name']} bus1={t['bus_a']} bus2={t['bus_b']} switch=yes")
        out.append(f"Open Line.{t['name']} term=1")
    pf = spec["consumers"]["power_factor"]
    frac = net["movable_fraction"]
    out.append("\n! Distribution transformers 11/0.415 kV, their load blocks and LV switches")
    by_feeder = {f["name"]: f for f in city["feeders"]}
    for tx in city["txs"]:
        t, lv, kva = tx["name"], tx["lv_bus"], tx["rating_kva"]
        kw = 0.5 * kva
        out.append(f"New Transformer.{t} phases=3 windings=2 buses=({tx['mv_bus']}, {lv}) conns=(delta, wye) "
                   f"kVs=(11, 0.415) kVAs=({kva}, {kva}) %loadloss=1 xhl=4")
        out.append(f"New Load.LD{t[1:]}a bus1={lv} phases=3 kV=0.415 kW={kw * (1 - frac):.1f} pf={pf[tx['type']]}")
        out.append(f"New Load.LD{t[1:]}b bus1={lv}b phases=3 kV=0.415 kW={kw * frac:.1f} pf={pf[tx['type']]}")
        out.append(f"New Line.SW{t[1:]}H bus1={lv}b bus2={lv} switch=yes")
        names = by_feeder[tx["feeder"]]["transformers"]
        i = names.index(t)
        to = names[i + 1] if i + 1 < len(names) else names[i - 1]
        tx["move_to"] = to
        out.append(f"New Line.SW{t[1:]}A bus1={lv}b bus2=L{to[1:]} switch=yes")
        out.append(f"Open Line.SW{t[1:]}A term=1")
    out += ["", "Set voltagebases=[11, 0.415]", "Calcvoltagebases"]
    return "\n".join(out) + "\n"


def grid_yaml(spec, city, rel_dss):
    pf = spec["consumers"]["power_factor"]
    subs = {s: {"id": f"SUB-{i + 1:03d}", "bus": s, "kv": 11} for i, s in enumerate(city["subs"])}
    feeders = {f["name"]: {"id": f"FD-{i + 1:03d}", "substation": f["substation"], "head_line": f"{f['name']}L1",
                           "transformers": f["transformers"], "buses": f["buses"]}
               for i, f in enumerate(city["feeders"])}
    txs = {tx["name"]: {"id": f"DT-{i + 1:03d}", "feeder": tx["feeder"], "mv_bus": tx["mv_bus"],
                        "rating_kva": tx["rating_kva"], "category": tx["type"],
                        "fixed_load": f"LD{tx['name'][1:]}a", "movable_load": f"LD{tx['name'][1:]}b"}
           for i, tx in enumerate(city["txs"])}
    switches, n = {}, 0

    def add(name, kind, normal, **extra):
        nonlocal n
        n += 1
        switches[name] = {"id": f"SW-{n:03d}", "kind": kind, "normal": normal, **extra}
    for tx in city["txs"]:
        add(f"SW{tx['name'][1:]}H", "lv_home", "closed")
    for tx in city["txs"]:
        add(f"SW{tx['name'][1:]}A", "lv_alt", "open")
    for f in city["feeders"]:
        if f["sec_after"] < len(f["buses"]):
            add(f"{f['name']}SEC", "mv_sectionaliser", "closed",
                buses=[f["buses"][f["sec_after"] - 1], f["buses"][f["sec_after"]]])
    for t in city["ties"]:
        add(t["name"], "mv_tie", "open", buses=[t["bus_a"], t["bus_b"]])
    moves = {tx["name"]: {"home": f"SW{tx['name'][1:]}H", "alt": f"SW{tx['name'][1:]}A", "to": tx["move_to"]}
             for tx in city["txs"]}
    mv, k = {}, 0
    by_feeder = {f["name"]: f for f in city["feeders"]}
    for t in city["ties"]:
        for far, other in ((t["a"], t["b"]), (t["b"], t["a"])):
            f = by_feeder[far]
            if f["sec_after"] >= len(f["buses"]):
                continue
            k += 1
            moved = f["transformers"][f["sec_after"]:]
            mv[f"MV{k}"] = {"open": f"{far}SEC", "close": t["name"], "feeders": [far, other],
                            "description": f"feed the far end of {far} ({', '.join(moved)}) from {other}"}
    # diagram layout: one row per feeder, substations on the left
    rows = {f["name"]: i for i, f in enumerate(city["feeders"])}
    layout = {"buses": {}, "transformers": {}}
    for f in city["feeders"]:
        y = -1.6 * rows[f["name"]]
        for j, b in enumerate(f["buses"], start=1):
            layout["buses"][b] = [float(j), y]
        for j, t in enumerate(f["transformers"], start=1):
            layout["transformers"][t] = [float(j), round(y + 0.6, 2)]
    for s in city["subs"]:
        ys = [-1.6 * rows[f["name"]] for f in city["feeders"] if f["substation"] == s]
        layout["buses"][s] = [-0.3, round(float(np.mean(ys)), 2)]
    return {"network_file": rel_dss, "substations": subs, "feeders": feeders,
            "load_categories": {k: {"power_factor": pf[k]} for k in TYPES},
            "transformers": txs, "load_split": {"movable_fraction": spec["network"]["movable_fraction"]},
            "switches": switches, "moves": moves, "mv_transfers": mv, "layout": layout}


def settings(spec, name):
    """The other config files of the city, starting from the classic ones."""
    ops = copy.deepcopy(config.operations())
    ops["rerouting"]["candidate_scope"] = "relevant"
    sc = {"benchmark": [{"name": s["name"], "rules": [], "events": list(s.get("events", []))}
                        for s in spec["scenarios"]],
          "quick": {"base_kw": 150, "scenarios": [{"name": "Flat load", "rules": []}]},
          "dashboard": [{"label": "Normal"}]}
    fc = {"source": "city", "intervals": copy.deepcopy(config.forecasting()["intervals"])}
    st = copy.deepcopy(config.storage())
    st["url"] = f"sqlite:///data/city_{name}.db"
    st["retention"] = {"measurements_days": 60, "alerts_days": 60, "forecasts_days": 60,   # a year is 35,040 steps
                       "meter_readings_days": 2}                       # ~5,000 smart-meter readings per step
    meters = meter_settings(spec)["enabled"]
    source = spec["simulation"].get("forecast_source", "short")
    st["forecast_import"] = {"model_version": "persistence-24h" if source == "persistence" else SHORT_VERSION,
                             "measurement_source": "dt-scada" if meters else "city-meters"}
    sim = copy.deepcopy(config.simulation())
    s = spec["simulation"]
    sim["city"] = name
    sim["clock"].update(start=s["start"], end=s["end"], step_minutes=int(s["step_minutes"]))
    sim["orchestrator"].update(scenario=s["scenario"], forecast_source=source)
    return {"operations": ops, "scenarios": sc, "forecasting": fc, "storage": st, "simulation": sim}


def generate(name):
    folder = city_dir(name)
    spec = load_spec(folder)
    city = build(spec)
    d = CityDemand(folder, consumers=None)
    consumers = size_consumers(spec, city, d)
    try:
        rel_dss = (folder / "network.dss").resolve().relative_to(ROOT).as_posix()
    except ValueError:                                       # a city outside the project (tests)
        rel_dss = (folder / "network.dss").resolve().as_posix()
    dss_text = network_dss(spec, city)
    (folder / "network.dss").write_text(dss_text, encoding="utf-8")
    tx_ids = {t: f"DT-{i + 1:03d}" for i, t in enumerate(tx["name"] for tx in city["txs"])}
    consumers.insert(3, "transformer_asset_id", consumers["transformer"].map(tx_ids))
    consumers.to_csv(folder / "consumers.csv", index=False)
    cfg = folder / "config"
    cfg.mkdir(exist_ok=True)
    files = {"grid": grid_yaml(spec, city, rel_dss), **settings(spec, folder.name)}
    for fname, data in files.items():
        (cfg / f"{fname}.yaml").write_text(HEADER + yaml.safe_dump(data, sort_keys=False, width=120), encoding="utf-8")
    g = files["grid"]
    return {"substations": len(g["substations"]), "feeders": len(g["feeders"]), "transformers": len(g["transformers"]),
            "switches": len(g["switches"]), "mv_transfers": len(g["mv_transfers"]), "consumers": len(consumers),
            "by_type": consumers["type"].value_counts().to_dict(),
            "capacity_kva": int(sum(t["rating_kva"] for t in g["transformers"].values()))}


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate a synthetic city from cities/<name>/city.yaml")
    ap.add_argument("name", nargs="?", default="demo")
    a = ap.parse_args(argv)
    summary = generate(a.name)
    print(f"City {a.name}: {summary}")


if __name__ == "__main__":
    main()
